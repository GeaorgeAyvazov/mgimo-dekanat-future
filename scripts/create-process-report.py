def register_fonts():
    folders = [
        Path(os.environ.get("REPORT_FONT_DIR", ".")),
        Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts",
        Path("/usr/share/fonts/truetype/dejavu"),
        Path("/usr/local/share/fonts"),
        Path.home() / "Library/Fonts",
    ]
    for folder in folders:
        regular = folder / "DejaVuSans.ttf"
        bold = folder / "DejaVuSans-Bold.ttf"
        if regular.is_file() and bold.is_file():
            pdfmetrics.registerFont(TTFont("Body", str(regular)))
            pdfmetrics.registerFont(TTFont("Strong", str(bold)))
            pdfmetrics.registerFontFamily("Body", normal="Body", bold="Strong")
            return
    raise RuntimeError("Install DejaVu Sans or set REPORT_FONT_DIR to its font folder.")


class Report:
    def __init__(self):
        register_fonts()
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        self.pdf = canvas.Canvas(str(OUTPUT), pagesize=A4, pageCompression=True)
        self.pdf.setCreator("Генератор конкурсного отчёта / ReportLab")
        self.pdf.setTitle("Деканат будущего. Как создавался прототип")
        self.pdf.setAuthor("Участники проекта «Деканат будущего»")
        self.pdf.setSubject("Конкурсный отчёт о процессе создания. Ноябрь 2026")
        self.page = 0

    def text(self, x, top, width, value, size=11, leading=None, color=INK, bold=False):
        style = ParagraphStyle("text", fontName="Strong" if bold else "Body",
                               fontSize=size, leading=leading or size * 1.46,
                               textColor=HexColor(color), splitLongWords=0)
        paragraph = Paragraph(value, style)
        _, height = paragraph.wrap(width, H)
        if top + height > H - 50:
            raise ValueError(f"Page {self.page} exceeds available height: {value[:70]}")
        paragraph.drawOn(self.pdf, x, H - top - height)
        return top + height

    def rule(self, top, left=M, width=COL):
        self.pdf.setStrokeColor(HexColor(LINE))
        self.pdf.setLineWidth(.65)
        self.pdf.line(left, H - top, left + width, H - top)

    def new(self, label, title, intro=None):
        if self.page:
            self.pdf.showPage()
        self.page += 1
        self.pdf.setFillColor(HexColor(BLUE))
        self.pdf.rect(M, H - 41, 18, 3, stroke=0, fill=1)
        self.text(M + 27, 30, 300, label.upper(), 8.2, color=BLUE, bold=True)
        self.pdf.setFillColor(HexColor(MUTED))
        self.pdf.setFont("Body", 8)
        self.pdf.drawRightString(W - M, H - 40, "НОЯБРЬ 2026")
        self.rule(55)
        self.pdf.setFillColor(HexColor(MUTED))
        self.pdf.setFont("Body", 8)
        self.pdf.drawString(M, 26, "Деканат будущего   /   Процесс создания")
        self.pdf.drawRightString(W - M, 26, str(self.page))
        self.rule(H - 43)
        self.pdf.bookmarkPage(f"p{self.page}")
        self.pdf.addOutlineEntry(title, f"p{self.page}", level=0)
        bottom = self.text(M, 75, COL, title, 35 if self.page == 1 else 26, bold=True, leading=43 if self.page == 1 else 34)
        if intro:
            bottom = self.text(M, bottom + 12, COL, intro, 12, leading=18.2, color=MUTED)
        return bottom

    def band(self, top, heading, body):
        bottom = self.text(M + 14, top + 11, COL - 28, heading, 10.8, bold=True, color=BLUE)
        bottom = self.text(M + 14, bottom + 3, COL - 28, body, 10.3, leading=15.3)
        self.pdf.setStrokeColor(HexColor(BLUE))
        self.pdf.setLineWidth(2)
        self.pdf.line(M + 2, H - top - 11, M + 2, H - bottom)
        return bottom + 10

    def section(self, top, title, content, x=M, width=COL):
        bottom = self.text(x, top, width, title, 13, leading=18, bold=True, color=BLUE)
        return self.text(x, bottom + 4, width, content, 10.8, leading=16.8)

    def photo(self, name, x, top, width, caption=None, crop=None):
        path = SCREENSHOTS / name
        with Image.open(path) as source:
            img = source.convert("RGB")
        if crop:
            img = img.crop(crop)
        height = width * img.height / img.width
        self.pdf.drawImage(ImageReader(img), x, H - top - height, width, height)
        self.pdf.setStrokeColor(HexColor(LINE))
        self.pdf.setLineWidth(.6)
        self.pdf.rect(x, H - top - height, width, height)
        if caption:
            return self.text(x, top + height + 7, width, caption, 8.7, leading=12.8, color=MUTED)
        return top + height

    def source(self, top, links):
        def anchor(item):
            name, url = item
            return f'<link href="{escape(url)}" color="{BLUE}"><u>{escape(name)}</u></link>'
        return self.text(M, top, COL, "   ·   ".join(map(anchor, links)), 9, leading=15, color=BLUE)

    def quote(self, top, quote, consequence):
        self.rule(top)
        left = self.text(M, top + 10, 197, "«" + escape(quote) + "»", 11, leading=16, bold=True)
        right = self.text(M + 215, top + 10, COL - 215, consequence, 10.6, leading=16)
        return max(left, right) + 8

    def save(self):
        self.pdf.save()
        PUBLIC.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(OUTPUT, PUBLIC)


